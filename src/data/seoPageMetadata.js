export function getSeoMetadata({ activePage, activeCategoryId, activeSubServiceId }) {
  if (activePage === 'service' && (activeCategoryId || activeSubServiceId)) {
    const rawSub = (activeSubServiceId || '').toLowerCase().trim();

    // 1. Direct subServiceId match
    if (rawSub) {
      let match = seoPageMetadata.find(item => item.subServiceId === rawSub);
      if (match) return match;

      // 2. Match aliases
      match = seoPageMetadata.find(item => item.aliases && item.aliases.some(alias => {
        const cleanAlias = alias.toLowerCase().replace(/\/$/, '');
        return cleanAlias.endsWith(`/${rawSub}`) || cleanAlias === rawSub;
      }));
      if (match) return match;

      // 3. Match path ends with rawSub
      match = seoPageMetadata.find(item => item.path && item.path.toLowerCase().replace(/\/$/, '').endsWith(`/${rawSub}`));
      if (match) return match;

      // 4. Singular / plural flexible match (e.g. ad-film vs ad-films)
      const subNorm = rawSub.replace(/s$/, '');
      match = seoPageMetadata.find(item => {
        if (!item.subServiceId) return false;
        const itemNorm = item.subServiceId.toLowerCase().replace(/s$/, '');
        return itemNorm === subNorm || item.subServiceId.toLowerCase().includes(rawSub) || rawSub.includes(item.subServiceId.toLowerCase());
      });
      if (match) return match;

      // 5. If we have a subServiceId but no exact item found, preserve the subservice URL
      if (activeCategoryId) {
        return {
          path: `/services/${activeCategoryId}/${rawSub}`,
          categoryId: activeCategoryId,
          subServiceId: rawSub,
          metaTitle: `${rawSub.split('-').map(w => w.charAt(0).toUpperCase() + w.slice(1)).join(' ')} | Digiworq`,
          metaDescription: `Professional ${rawSub.split('-').join(' ')} services in Bangalore by Digiworq.`
        };
      }
    }

    // Category level match
    if (activeCategoryId) {
      const match = seoPageMetadata.find(item => item.categoryId === activeCategoryId && !item.subServiceId);
      if (match) return match;
    }
  }

  const matchByPage = seoPageMetadata.find(item => item.pageKey === activePage);
  if (matchByPage) return matchByPage;

  // Default fallback to item 1
  return seoPageMetadata[0];
}

export function parseRouteFromUrl(pathname = window.location.pathname) {
  const normalizedPath = pathname.toLowerCase().replace(/\/$/, '') || '/';
  
  const matchedMeta = seoPageMetadata.find(item => {
    if (item.path.toLowerCase() === normalizedPath) return true;
    if (item.aliases && item.aliases.some(alias => alias.toLowerCase().replace(/\/$/, '') === normalizedPath)) return true;
    return false;
  });

  if (matchedMeta) {
    if (matchedMeta.pageKey) {
      return { activePage: matchedMeta.pageKey, activeCategoryId: '', activeSubServiceId: '' };
    }
    return {
      activePage: 'service',
      activeCategoryId: matchedMeta.categoryId || '',
      activeSubServiceId: matchedMeta.subServiceId || ''
    };
  }

  // Direct safety routes for core pages
  if (normalizedPath === '/e-commerce' || normalizedPath === '/ecommerce' || normalizedPath === '/shop') {
    return { activePage: 'ecommerce', activeCategoryId: '', activeSubServiceId: '' };
  }
  if (normalizedPath === '/blog' || normalizedPath === '/blogs' || normalizedPath === '/blog-posts') {
    return { activePage: 'blog', activeCategoryId: '', activeSubServiceId: '' };
  }
  if (normalizedPath === '/about' || normalizedPath === '/about-us') {
    return { activePage: 'about', activeCategoryId: '', activeSubServiceId: '' };
  }
  if (normalizedPath === '/our-works' || normalizedPath === '/works' || normalizedPath === '/portfolio') {
    return { activePage: 'works', activeCategoryId: '', activeSubServiceId: '' };
  }
  if (normalizedPath === '/contact' || normalizedPath === '/contact-us') {
    return { activePage: 'contact', activeCategoryId: '', activeSubServiceId: '' };
  }
  if (normalizedPath === '/career' || normalizedPath === '/careers') {
    return { activePage: 'career', activeCategoryId: '', activeSubServiceId: '' };
  }
  if (normalizedPath === '/services') {
    return { activePage: 'services', activeCategoryId: '', activeSubServiceId: '' };
  }

  if (normalizedPath.startsWith('/services/')) {
    const parts = normalizedPath.split('/').filter(Boolean);
    if (parts.length === 2) {
      return { activePage: 'service', activeCategoryId: parts[1], activeSubServiceId: '' };
    }
    if (parts.length >= 3) {
      return { activePage: 'service', activeCategoryId: parts[1], activeSubServiceId: parts[parts.length - 1] };
    }
  }

  return { activePage: 'home', activeCategoryId: 'creative', activeSubServiceId: '' };
}

